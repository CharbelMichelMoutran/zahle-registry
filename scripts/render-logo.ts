/**
 * Draw the "Zahle on Record" logo once, into src/components/ui/logo-data.ts
 * (DESIGN.md section 15).
 *
 * The construction: Arabic زحلة (Markazi Text 500) and English "on record"
 * (IBM Plex Serif 500) share one line. The line leaves the lower stroke of the
 * ح where it meets the baseline, at that stroke's thickness, thins as it runs
 * through the tail of ز, turns from ink to river blue, and becomes the line
 * "on record" sits on. One pen gesture, from the Arabic into the English.
 *
 * The letters are outlined here with HarfBuzz, the shaping engine browsers use,
 * so the Arabic joins exactly as it should and the logo draws the same on every
 * device, with no web font to load. Run again only to change the drawing:
 *
 *   npm run render:logo
 *
 * Fonts: Markazi Text and IBM Plex Serif, SIL Open Font License, from Google Fonts.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import * as hb from "harfbuzzjs";

const FONTS = {
  arabic: "https://github.com/google/fonts/raw/main/ofl/markazitext/MarkaziText%5Bwght%5D.ttf",
  latin: "https://github.com/google/fonts/raw/main/ofl/ibmplexserif/IBMPlexSerif-Medium.ttf",
};
const OUT = "src/components/ui/logo-data.ts";

/** Arabic size in drawing units. Everything else is measured against it. */
const AR_SIZE = 200;
const AR_WEIGHT = 500;

/**
 * Two cuts of the same drawing. "large" for the landing page and sign-in
 * screens; "small" for the top bar, where the English is set relatively larger
 * and the line thicker, so both still read at about 30 px tall.
 */
const CUTS = {
  large: { enRatio: 0.42, line: 5.5, gap: 16, lift: 3 },
  small: { enRatio: 0.54, line: 9, gap: 14, lift: 4 },
} as const;

/** Where the line leaves the ح, and where the blue has fully taken over (drawing units). */
const FORK_X = 148;
const BLUE_FROM = 252;
const BLUE_TO = 330;

async function fontFile(url: string) {
  const dir = join(tmpdir(), "zahle-logo-fonts");
  const file = join(dir, decodeURIComponent(url.split("/").pop()!));
  if (!existsSync(file)) {
    const res = await fetch(url);
    if (!res.ok) throw new Error(`Could not download ${url} (${res.status})`);
    await mkdir(dir, { recursive: true });
    await writeFile(file, Buffer.from(await res.arrayBuffer()));
  }
  return readFile(file);
}

const num = (n: number) => Number(n.toFixed(2));

/** Shape `text` and return one SVG path, y down, baseline at 0, starting at x = 0. */
function outline(data: Buffer, text: string, size: number, weight?: number) {
  const face = new hb.Face(new hb.Blob(data));
  const font = new hb.Font(face);
  if (weight) font.setVariations([new hb.Variation("wght", weight)]);
  const s = size / face.upem;
  const buffer = new hb.Buffer();
  buffer.addText(text);
  buffer.guessSegmentProperties();
  hb.shape(font, buffer);
  const positions = buffer.getGlyphPositions();
  let x = 0;
  let d = "";
  buffer.getGlyphInfos().forEach((glyph, i) => {
    const p = positions[i];
    const ox = (x + p.xOffset) * s;
    const oy = -p.yOffset * s;
    d += font.glyphToPath(glyph.codepoint).replace(/([MLQCZ])([^MLQCZ]*)/g, (_m: string, cmd: string, args: string) => {
      const n = args.trim() ? args.trim().split(/[ ,]+/).map(Number) : [];
      const out: number[] = [];
      for (let k = 0; k < n.length; k += 2) out.push(num(ox + n[k] * s), num(oy - n[k + 1] * s));
      return cmd + out.join(" ");
    });
    x += p.xAdvance;
  });
  return { d, width: x * s };
}

async function main() {
  const [arabicData, latinData] = await Promise.all([fontFile(FONTS.arabic), fontFile(FONTS.latin)]);
  const ar = outline(arabicData, "زحلة", AR_SIZE, AR_WEIGHT);

  const cuts = Object.fromEntries(
    Object.entries(CUTS).map(([name, c]) => {
      const en = outline(latinData, "on record", AR_SIZE * c.enRatio);
      const enX = num(ar.width + c.gap);
      const end = num(enX + en.width + 4);
      const t = c.line;
      // The line: flat underside on the baseline; its top falls from inside the ح's
      // lower stroke down to the line's own thickness, then runs straight to the end.
      const line =
        `M${FORK_X - 8} 0.6 H${end} ` +
        `A${t / 2} ${t / 2} 0 0 0 ${end} ${num(0.6 - t)} ` +
        `H${BLUE_FROM} C${FORK_X + 70} ${num(0.6 - t)} ${FORK_X + 40} -7 ${FORK_X} -9 Z`;
      return [
        name,
        {
          en: en.d,
          enX,
          enY: num(0.6 - t - c.lift),
          line,
          /** Centre of the line's round end, where the landing ribbon carries on. */
          end: { x: end, y: num(0.6 - t / 2) },
          thickness: t,
          viewBox: [-4, -132, num(end + t / 2 + 6), 184] as const,
        },
      ];
    }),
  );

  const body =
    `// Generated by scripts/render-logo.ts. Do not edit by hand; run \`npm run render:logo\`.\n` +
    `// Markazi Text and IBM Plex Serif outlines, SIL Open Font License.\n\n` +
    `export const LOGO_ARABIC = ${JSON.stringify(ar.d)};\n\n` +
    `export const LOGO_BLUE = { from: ${BLUE_FROM}, to: ${BLUE_TO} } as const;\n\n` +
    `export const LOGO_CUTS = ${JSON.stringify(cuts, null, 2)} as const;\n`;
  await writeFile(OUT, body);
  console.log(`Saved ${OUT}.`);
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
